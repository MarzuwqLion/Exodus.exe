export interface Glyph {
  w: number;
  rows: Rows;
}

export interface BitmapFont {
  name: 'text' | 'num';
  height: number;
  lineHeight: number;
  /** Space between glyphs. */
  spacing: number;
  glyphs: Map<string, Glyph>;
  fallback: Glyph;
}

function build(
  name: 'text' | 'num',
  src: Record<string, Rows>,
  height: number,
  lineHeight: number,
): BitmapFont {
  const glyphs = new Map<string, Glyph>();
  for (const [ch, rows] of Object.entries(src)) {
    const w = Math.max(...rows.map((r) => r.length));
    glyphs.set(ch, { w, rows });
  }
  const fallback = glyphs.get('?') ?? glyphs.get(' ')!;
  return { name, height, lineHeight, spacing: 1, glyphs, fallback };
}

export const TEXT_FONT = build('text', T, 8, 10);
export const NUM_FONT = build('num', N, 5, 7);

export function normalizeChar(ch: string): string {
  return NORMALIZE[ch] ?? ch;
}

/** The key of the glyph that renders `ch` (after normalization and fallbacks). */
export function glyphKey(font: BitmapFont, ch: string): string {
  const c = normalizeChar(ch);
  if (font.glyphs.has(c)) return c;
  const up = c.toUpperCase();
  if (font.glyphs.has(up)) return up;
  return font.glyphs.has('?') ? '?' : ' ';
}

export function glyphFor(font: BitmapFont, ch: string): Glyph {
  return font.glyphs.get(glyphKey(font, ch)) ?? font.fallback;
}

/** Pixel width of a single line of text. */
export function measure(font: BitmapFont, text: string): number {
  let w = 0;
  let first = true;
  for (const ch of text) {
    if (!first) w += font.spacing;
    w += glyphFor(font, ch).w;
    first = false;
  }
  return w;
}

/** Greedy word wrap to a pixel width. Respects explicit newlines. */
export function wrap(font: BitmapFont, text: string, maxWidth: number): string[] {
  const out: string[] = [];
  for (const para of text.split('\n')) {
    const words = para.split(' ');
    let line = '';
    for (const word of words) {
      const candidate = line ? line + ' ' + word : word;
      if (measure(font, candidate) <= maxWidth || !line) {
        line = candidate;
      } else {
        out.push(line);
        line = word;
      }
    }
    out.push(line);
  }
  return out;
}
